function renderGlance() {
  const max = Math.max(
    ...[0, 1].flatMap((i) => ["revenue", "profit"].map((k) => Math.abs(value(i, k) || 0))),
    1,
  );
  const row = (k) => {
    const label = DEF_BY[k][1];
    const v0 = value(0, k),
      v1 = value(1, k);
    return (
      '<div class="chart-row"><div class="lab"><span>' +
      label +
      "</span><span>" +
      state.years[0] +
      " <b>" +
      fmt(v0) +
      "</b> · " +
      state.years[1] +
      " <b>" +
      fmt(v1) +
      "</b></span></div>" +
      (v0 == null
        ? ""
        : '<div class="bar" style="width:' +
          ((Math.abs(v0) / max) * 100).toFixed(1) +
          '%;background:#0e5a3c"></div>') +
      (v1 == null
        ? ""
        : '<div class="bar" style="width:' +
          ((Math.abs(v1) / max) * 100).toFixed(1) +
          '%;background:#b9bcb2"></div>') +
      "</div>"
    );
  };
  const panel = document.querySelector(".bottom .panel");
  panel.innerHTML =
    '<div class="head"><h2>The year at a glance</h2><span>revenue · net profit · same basis</span></div>' +
    row("revenue") +
    row("profit") +
    '<div class="legend"><span><i style="background:#0e5a3c"></i>' +
    state.years[0] +
    ' · current year</span><span><i style="background:#b9bcb2"></i>' +
    state.years[1] +
    " · prior year as presented</span></div>";
}
function renderChanges() {
  const panel = document.querySelectorAll(".bottom .panel")[1];
  panel.innerHTML =
    '<div class="head"><h2>What changed?</h2><span>calculated from workspace figures</span></div>' +
    ["revenue", "profit", "cash"]
      .map((k) => {
        const d = change(k),
          name = DEF_BY[k][1];
        const body =
          d == null
            ? "A comparable pair of figures is not yet available."
            : "<b>" +
              (d >= 0 ? "Increased" : "Decreased") +
              ' <b class="' +
              (d >= 0 ? "up" : "down") +
              '">' +
              Math.abs(d).toFixed(1) +
              "%</b></b> from " +
              state.years[1] +
              " to " +
              state.years[0] +
              ".";
        return (
          '<div class="change"><b>' +
          name +
          "</b> " +
          body +
          '<div class="why">change = (current ÷ prior − 1) × 100, shown only when the prior value is positive</div></div>'
        );
      })
      .join("");
}

/* ------------------------------------------------------ strategy contract -- */
/* Mirrors calculations.js (the verified strategy engine): gross return, max
   drawdown, net return with a two-transaction fee approximation. */
function strategyMath(prices, feeBps) {
  let peak = prices[0],
    dd = 0;
  for (const p of prices) {
    peak = Math.max(peak, p);
    dd = Math.max(dd, ((peak - p) / peak) * 100);
  }
  const gross = (prices[prices.length - 1] / prices[0] - 1) * 100;
  return { grossReturnPct: gross, maxDrawdownPct: dd, netReturnPct: gross - (feeBps * 2) / 100 };
}
function samplePrices() {
  // deterministic two-year path, seeded by company
  let h = 2166136261 >>> 0;
  const s = state.company || "demo";
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619) >>> 0;
  }
  let a = h >>> 0;
  const r = () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const out = [];
  let p = 10;
  for (let i = 0; i < 490; i++) {
    p = Math.max(0.5, p * (1 + 0.00035 + (r() - 0.5) * 0.021));
    out.push(+p.toFixed(2));
  }
  return out;
}
async function renderMarket() {
  let prices,
    feeBps = 10,
    src;
  if (bridge.on) {
    try {
      const inputs = await Promise.race([
        cd80.call("storage.read", { key: "inputs" }),
        timeout(2500),
      ]);
      if (inputs && Array.isArray(inputs.prices) && inputs.prices.length > 1) {
        prices = inputs.prices;
        feeBps = typeof inputs.feeBps === "number" ? inputs.feeBps : 10;
        src = "platform shared series";
      }
    } catch {
      /* fall through to sample */
    }
  }
  if (!prices) {
    prices = samplePrices();
    src = "deterministic sample series · not market quotes";
  }
  const m = strategyMath(prices, feeBps);
  $("mk-basis").textContent =
    src + " · " + prices.length + " points · fee " + feeBps + " bps/transaction";
  const min = Math.min(...prices),
    max = Math.max(...prices),
    span = max - min || 1;
  const W = 900,
    H = 210,
    P = 42,
    n = prices.length;
  const x = (i) => P + (i * (W - 2 * P)) / (n - 1);
  const y = (v) => H - 26 - ((v - min) / span) * (H - 52);
  let grid = "";
  for (let k = 0; k <= 3; k++) {
    const v = min + (span * k) / 3;
    grid +=
      '<line class="grid-l" x1="' +
      P +
      '" y1="' +
      y(v).toFixed(1) +
      '" x2="' +
      (W - P) +
      '" y2="' +
      y(v).toFixed(1) +
      '"/>' +
      '<text class="axis" x="' +
      (P - 8) +
      '" y="' +
      (y(v) + 3.5).toFixed(1) +
      '" text-anchor="end">' +
      v.toFixed(2) +
      "</text>";
  }
  const pts = prices.map((v, i) => x(i).toFixed(1) + "," + y(v).toFixed(1)).join(" ");
  $("mk-chart").innerHTML =
    grid +
    '<path class="area" d="M' +
    P +
    "," +
    (H - 26) +
    " L" +
    pts.split(" ").join(" L") +
    " L" +
    x(n - 1).toFixed(1) +
    "," +
    (H - 26) +
    ' Z"/>' +
    '<polyline class="line" points="' +
    pts +
    '"/>';
  const sign = (v) => (v >= 0 ? "+" : "");
  $("mk-stats").innerHTML =
    '<div><div class="k">Gross return · ' +
    state.years[1] +
    "→" +
    state.years[0] +
    '</div><div class="v ' +
    (m.grossReturnPct >= 0 ? "up" : "down") +
    '">' +
    sign(m.grossReturnPct) +
    m.grossReturnPct.toFixed(1) +
    "%</div></div>" +
    '<div><div class="k">Net of fees</div><div class="v ' +
    (m.netReturnPct >= 0 ? "up" : "down") +
    '">' +
    sign(m.netReturnPct) +
    m.netReturnPct.toFixed(1) +
    "%</div></div>" +
    '<div><div class="k">Max drawdown</div><div class="v down">−' +
    m.maxDrawdownPct.toFixed(1) +
    "%</div></div>";
}
function timeout(ms) {
  return new Promise((_, reject) => setTimeout(() => reject(new Error("timeout")), ms));
}

/* ------------------------------------------------------------- evidence -- */
function evidence(k) {
  const keys = k === "margin" ? ["revenue", "profit"] : [k];
  $("detailBody").innerHTML =
    "<h3>" +
    (k === "margin" ? "Net profit margin" : DEF_BY[k][1]) +
    " · evidence</h3>" +
    '<p class="fine">Every figure points at the line it came from. Choose a different number to reassign it — the change is manual and checked against the row. Missing values are never estimated.</p>' +
    keys
      .map((key) =>
        [0, 1]
          .map((i) => {
            const r = (state.records[i] || {})[key];
            const m = r && r.matches && r.matches.length ? r.matches : r ? [r] : [];
            return (
              '<div class="review"><b>' +
              state.years[i] +
              " · " +
              DEF_BY[key][1] +
              "</b>" +
              (r
                ? '<p class="fine">Selected: ' +
                  fmt(r.value) +
                  (r.basis ? " · " + esc(r.basis) : "") +
                  "</p>"
                : '<p class="fine">No source in this workspace.</p>') +
              m
                .map(
                  (hit, hi) =>
                    "<pre>" +
                    esc(hit.line) +
                    "</pre>" +
                    hit.candidates
                      .map(
                        (c, ci) =>
                          '<button class="pick" data-y="' +
                          i +
                          '" data-k="' +
                          key +
                          '" data-h="' +
                          hi +
                          '" data-c="' +
                          ci +
                          '">Use ' +
                          esc(c.raw) +
                          "</button>",
                      )
                      .join(""),
                )
                .join("") +
              "</div>"
            );
          })
          .join(""),
      )
      .join("");
  $("detailBody")
    .querySelectorAll(".pick")
    .forEach((b) => {
      b.onclick = () => {
        const rec = state.records[+b.dataset.y][b.dataset.k];
        const hit = (rec.matches && rec.matches.length ? rec.matches : [rec])[+b.dataset.h];
        state.records[+b.dataset.y][b.dataset.k] = {
          ...rec,
          line: hit.line,
          value: hit.candidates[+b.dataset.c].num,
          basis: "manually assigned from a matching row",
        };
        fire(render());
        evidence(k);
      };
    });
  $("detail").showModal();
}
function explain(k) {
  const d = DEF_BY[k];
  $("detailBody").innerHTML =
    "<h3>" +
    d[1] +
    '</h3><p class="sec">' +
    esc(d[2]) +
    "</p>" +
    '<p class="sec">No universal good or bad threshold applies. A valid industry comparison needs sourced peers with the same period, accounting definition and reporting scope; peer data is unavailable here.</p>' +
    '<p class="sec">Year-over-year change = (current ÷ prior − 1) × 100, only when the prior value is positive. Margin changes are percentage points. Changes describe the figures and do not explain their causes.</p>';
  $("detail").showModal();
}
function wireCards() {
  document.querySelectorAll(".info").forEach((b) => {
    b.onclick = () => explain(b.dataset.x);
  });
  document.querySelectorAll(".ev").forEach((b) => {
    b.onclick = () => evidence(b.dataset.ev);
  });
}

