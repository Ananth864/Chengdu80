function numbers(text) {
  return [...text.matchAll(/\(?[−+-]?\d[\d,]*(?:\.\d+)?\)?/g)]
    .map((m) => ({
      raw: m[0],
      num: Number(m[0].replace(/[,()]/g, "").replace("−", "-")) * (m[0].startsWith("(") ? -1 : 1),
    }))
    .filter((v) => Number.isFinite(v.num));
}
function fmt(v, ratio) {
  if (v == null) return "Unavailable";
  if (ratio) return v.toFixed(1) + "%";
  const a = Math.abs(v);
  const c = state.currency;
  return (
    c +
    " " +
    (a >= 1e9
      ? (v / 1e9).toFixed(2) + "bn"
      : a >= 1e6
        ? (v / 1e6).toFixed(1) + "m"
        : v.toLocaleString("en-US", { maximumFractionDigits: 1 }))
  );
}
function value(i, key) {
  const r = state.records[i] || {};
  if (key === "margin") {
    const p = r.profit,
      rev = r.revenue;
    return p && p.value != null && rev && rev.value > 0 ? (p.value / rev.value) * 100 : null;
  }
  return r[key] && r[key].value != null ? r[key].value : null;
}
function change(k) {
  const a = value(0, k),
    b = value(1, k);
  if (a == null || b == null) return null;
  return k === "margin" ? a - b : b > 0 ? (a / b - 1) * 100 : null;
}

/* --------------------------------------------------------------- parsing -- */
function parseText(text, year) {
  const lines = text.split(/\r?\n/);
  const records = {};
  for (const [key, , , pattern] of defs) {
    if (!pattern) continue;
    const re = new RegExp(
      "^\\s*(?:[一二三四五六七八九十]+[、.．]\\s*|\\(?[a-z]\\)[. ]*)?(?:" +
        pattern +
        ")(?![a-z\\u4e00-\\u9fff])",
      "i",
    );
    const hits = [];
    lines.forEach((line, n) => {
      const cleaned = line
        .replace(/\u00a0/g, " ")
        .replace(/\s+/g, " ")
        .trim();
      const m = cleaned.match(re);
      if (!m) return;
      let tail = cleaned.slice(m[0].length).replace(/^\s*[:：]?\s*/, "");
      if (!/\d/.test(tail)) {
        // value may sit on the following line
        for (let j = n + 1; j < Math.min(n + 4, lines.length); j++) {
          const t = lines[j].trim();
          if (/^[\d\s,.()−+\-—$¥￥€£%]+$/.test(t)) {
            tail = t;
            break;
          }
          if (t) break;
        }
      }
      tail = tail
        .replace(/^\s*\[(?:\d+|[a-z]+)\]\s*/i, "")
        .replace(/^\s*\((?:note\s*)?\d+\)\s*/i, "")
        .replace(/\.{2,}/g, " ");
      if (!/^[\d\s,.()−+\-—$¥￥€£%:：]*$/.test(tail) || tail.includes("%")) return;
      const candidates = numbers(tail);
      if (!candidates.length) return;
      let chosen = null;
      for (let j = n - 1; j >= Math.max(0, n - 8); j--) {
        const ys = [...lines[j].matchAll(/\b(?:19|20)\d{2}\b/g)].map((x) => +x[0]);
        if (ys.length >= 2) {
          if (ys.length === candidates.length && ys.filter((y) => y === year).length === 1)
            chosen = ys.indexOf(year);
          break;
        }
      }
      hits.push({
        line: cleaned,
        candidates,
        col: chosen,
        value: chosen != null ? candidates[chosen].num : null,
      });
    });
    if (hits.length) {
      const assumed = hits.filter((h) => h.col == null && h.candidates.length === 2);
      const resolved = hits.filter((h) => h.value != null);
      const vals = [...new Set(resolved.map((h) => h.value))];
      records[key] = {
        ...hits[0],
        value: vals.length === 1 && resolved.length === hits.length ? vals[0] : null,
        matches: hits,
        assumedColumnOrder: assumed.length === hits.length && hits.length === 1,
      };
    }
  }
  return records;
}
function assumedAssign(records, yearIndex) {
  // Without a year header, comparative statements conventionally show the
  // current year first. Assign that way but keep the choice visible.
  for (const key of Object.keys(records)) {
    const r = records[key];
    if (r.value == null && r.assumedColumnOrder && r.candidates.length === 2) {
      r.value = r.candidates[yearIndex].num;
      r.basis =
        yearIndex === 0
          ? "first column assumed current year — verify in evidence"
          : "second column assumed prior year — verify in evidence";
    }
  }
  return records;
}

/* ------------------------------------------------------------ workspaces -- */
function demoState() {
  const years = [2025, 2024];
  const vs = [
    [128.4, 18.6, 23.1, 182.5, 67.2],
    [112.8, 14.2, 25.4, 169.3, 64.8],
  ];
  const records = vs.map((row, i) => {
    const rec = {};
    row.forEach((v, j) => {
      rec[defs[j][0]] = {
        value: v * 1e6,
        page: 1,
        line: "FICTIONAL EXAMPLE · " + years[i] + " · CNY millions — " + defs[j][1] + ": " + v,
        candidates: [{ raw: String(v), num: v }],
        matches: [],
      };
    });
    return rec;
  });
  return { years, currency: "CNY", unit: 1e6, records, demo: true, company: "Northstar Studio" };
}
function clearState() {
  return {
    years: [2025, 2024],
    currency: "CNY",
    unit: 1e6,
    records: [{}, {}],
    demo: false,
    company: "Your company",
  };
}

/* --------------------------------------------------------------- render -- */
function deltaChip(k) {
  const d = change(k);
  if (d == null) return '<span class="delta flat">Comparison unavailable</span>';
  if (k === "margin")
    return (
      '<span class="delta' +
      (d < 0 ? " down" : d === 0 ? " flat" : "") +
      '">' +
      (d >= 0 ? "+" : "") +
      d.toFixed(1) +
      " pp year over year</span>"
    );
  return (
    '<span class="delta' +
    (d < 0 ? " down" : d === 0 ? " flat" : "") +
    '">' +
    (d >= 0 ? "+" : "") +
    d.toFixed(1) +
    "% year over year</span>"
  );
}
function evLabel(key, i) {
  if (key === "margin") return "derived ↗";
  const r = state.records[i] && state.records[i][key];
  if (!r) return "no source";
  return state.demo
    ? "p.1 · row " + (defs.findIndex((d) => d[0] === key) + 3) + " ↗"
    : "text line ↗";
}
async function render() {
  $("company").value = state.company;
  $("period").textContent = state.years.join(" vs ");
  const notice = $("notice");
  if (state.demo) {
    notice.className = "banner demo";
    notice.innerHTML =
      '<b class="demo-k">Example workspace.</b> Fictional figures for Northstar Studio. Paste report text from your own annual report to replace this example — every figure keeps a citation to the line it came from.';
    $("mode-note").textContent = "Example workspace · fictional figures";
  } else if (state.parsed) {
    const found = [0, 1].reduce(
      (n, i) => n + defs.slice(0, 5).filter((d) => value(i, d[0]) != null).length,
      0,
    );
    notice.className = "banner";
    notice.innerHTML =
      "<b>Pasted report read.</b> " +
      found +
      " of 10 source figures resolved for " +
      state.years.join(" vs ") +
      " · " +
      state.currency +
      ". Open any metric\u2019s evidence to review candidate rows and assign the right figure. Unresolved figures stay unavailable — nothing is estimated.";
    $("mode-note").textContent = "Pasted report · " + found + "/10 figures";
  } else {
    notice.className = "banner";
    notice.innerHTML =
      "<b>Workspace empty.</b> Load the fictional example or paste income-statement and balance-sheet text from one annual report to begin.";
    $("mode-note").textContent = "Workspace · empty";
  }
  $("metrics").innerHTML = defs
    .map(
      ([k, title]) =>
        '<article class="card"><div class="head">' +
        title +
        ' <button class="info" data-x="' +
        k +
        '" aria-label="Explain ' +
        title +
        '">i</button></div>' +
        '<div class="value' +
        (value(0, k) == null ? " na" : "") +
        '">' +
        (value(0, k) == null ? "Unavailable" : fmt(value(0, k), k === "margin")) +
        "</div>" +
        deltaChip(k) +
        '<div class="prior">' +
        state.years[1] +
        ": <b>" +
        (value(1, k) == null ? "—" : fmt(value(1, k), k === "margin")) +
        "</b></div>" +
        '<button class="ev" data-ev="' +
        k +
        '">' +
        evLabel(k, 0) +
        "</button></article>",
    )
    .join("");
  wireCards();
  renderGlance();
  renderChanges();
  await renderMarket();
}
