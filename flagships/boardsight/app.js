$("r-go").onclick = () => {
  const text = $("r-text").value;
  const year = Number($("r-year").value);
  const status = $("r-status");
  status.className = "error";
  if (!text.trim()) {
    status.textContent =
      "Paste some report text first — the income statement and balance sheet pages are enough.";
    return;
  }
  if (!Number.isInteger(year) || year < 1901 || year > 2200) {
    status.textContent = "Enter the financial year of the report (e.g. 2025).";
    return;
  }
  const cur = parseText(text, year);
  const prior = parseText(text, year - 1);
  assumedAssign(cur, 0);
  assumedAssign(prior, 1);
  const found = Object.keys(cur).length + Object.keys(prior).length;
  if (!found) {
    status.textContent =
      "No recognisable metric rows found. Look for lines like “Total revenue 128,455,302 112,830,177” and keep both year columns.";
    return;
  }
  state = {
    years: [year, year - 1],
    currency: "CNY",
    unit: 1e6,
    records: [cur, prior],
    demo: false,
    parsed: true,
    company: state.company === "Northstar Studio" ? "Your company" : state.company,
  };
  status.textContent = "";
  $("report").close();
  fire(render());
};

/* ------------------------------------------------------------- boot -- */
async function probeBridge() {
  if (typeof cd80 === "undefined") return;
  try {
    await Promise.race([cd80.call("storage.read", { key: "inputs" }), timeout(2500)]);
    bridge.on = true;
  } catch {
    bridge.on = false;
  }
}
async function boot() {
  await probeBridge();
  state = demoState();
  await render();
  if (typeof cd80 !== "undefined") cd80.ready();
}
